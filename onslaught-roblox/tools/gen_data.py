"""Generate Luau data modules from the shared JSON (the same files the HTML build uses).

Usage: python3 tools/gen_data.py
"""
import json
import math
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[2]
out = root / "onslaught-roblox" / "src" / "shared" / "Onslaught"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def lua(v, ind=0):
    pad = "\t" * (ind + 1)
    if v is None:
        return "nil"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (int, float)):
        if isinstance(v, float) and math.isinf(v):
            return "math.huge" if v > 0 else "-math.huge"
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        if not v:
            return "{}"
        if all(not isinstance(x, (dict, list)) for x in v):
            return "{ " + ", ".join(lua(x) for x in v) + " }"
        return "{\n" + "".join(f"{pad}{lua(x, ind + 1)},\n" for x in v) + "\t" * ind + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        items = []
        for k, x in v.items():
            if x is None:
                continue
            key = k if IDENT.match(k) else "[" + json.dumps(k) + "]"
            items.append(f"{pad}{key} = {lua(x, ind + 1)},\n")
        return "{\n" + "".join(items) + "\t" * ind + "}"
    raise TypeError(type(v))


for src, name in (("game.json", "Data"), ("expansion.json", "ExpansionData")):
    data = json.loads((root / "onslaught-data" / src).read_text())
    body = f"-- Generated by tools/gen_data.py from onslaught-data/{src}. Do not edit by hand.\nreturn " + lua(data) + "\n"
    (out / f"{name}.luau").write_text(body)
    print("wrote", out / f"{name}.luau", len(body), "bytes")
