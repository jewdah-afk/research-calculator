#!/usr/bin/env node
/**
 * build-tower-data.js — regenerates data/tower-data.js from the TowerSmith
 * "GOD tables" (https://github.com/AngryBrit/tower-smith, CC BY-NC-SA 4.0),
 * which are themselves extracted from the game's own upgrade tables.
 *
 * Usage:  node tools/build-tower-data.js <path-to-tower-smith-checkout>
 *
 * Emits, for every Workshop stat and every Lab research, the exact per-level
 * marginal cost / displayed value arrays. Nothing here is interpolated.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = process.argv[2];
if (!ROOT) { console.error('usage: build-tower-data.js <tower-smith checkout>'); process.exit(1); }

const read = f => JSON.parse(fs.readFileSync(f, 'utf8'));
const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(e =>
  e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]);

// ---- Workshop: 48 base stats, plus the enhancement layer -------------------
function workshop() {
  const out = {};
  for (const cat of ['attack', 'defense', 'utility']) {
    for (const file of fs.readdirSync(path.join(ROOT, 'tables/workshop', cat))) {
      const j = read(path.join(ROOT, 'tables/workshop', cat, file));
      const key = file.replace(/\.json$/, '');
      out[key] = {
        n: j.name,
        c: cat,
        max: j.maxLevel,
        // cost[i] = coins to go from level i to level i+1
        cost: j.levels.map(l => (l.nextCoins ? l.nextCoins.coins : 0)).slice(0, j.maxLevel),
        val: j.levels.map(l => l.value),
        disp: j.levels[1] && j.levels[1].valueDisplay ? 'pct' : 'num'
      };
    }
  }
  return out;
}

// ---- Labs: exact coins / seconds / gems per level --------------------------
function labs() {
  const out = {};
  const base = path.join(ROOT, 'tables/labs');
  for (const file of walk(base)) {
    if (!file.endsWith('.json') || file.endsWith('lab-order.json')) continue;
    const j = read(file);
    if (!Array.isArray(j.levels)) continue;
    const cat = path.relative(base, path.dirname(file));
    const key = cat + '/' + path.basename(file, '.json');
    out[key] = {
      n: j.name,
      c: cat,
      max: j.maxLevel,
      cost: j.levels.map(l => l.coins || 0),
      time: j.levels.map(l => (l.time ? l.time.seconds : 0)),
      gems: j.levels.map(l => l.gems || 0),
      val: j.levels.map(l => l.value)
    };
  }
  return out;
}

// Displayed stat values are floats with long tails — trim them to 6 significant
// digits to keep the shipped file small. Costs, durations and gem counts are
// NOT trimmed: they are summed over thousands of levels, where 1e-6 relative
// noise per term accumulates into a visible drift.
function trim(x) {
  if (typeof x !== 'number' || !isFinite(x) || Number.isInteger(x)) return x;
  return Number(x.toPrecision(6));
}
function trimAll(o) {
  for (const s of Object.values(o)) for (const k of ['val'])
    if (Array.isArray(s[k])) s[k] = s[k].map(trim);
  return o;
}

const data = { generated: new Date().toISOString().slice(0, 10), workshop: trimAll(workshop()), labs: trimAll(labs()) };
const dest = path.join(__dirname, '..', 'data', 'tower-data.js');
fs.writeFileSync(dest,
  '// GENERATED by tools/build-tower-data.js — do not hand-edit.\n' +
  '// Source: TowerSmith GOD tables (AngryBrit/tower-smith, CC BY-NC-SA 4.0),\n' +
  '// extracted from The Tower\'s own upgrade tables. See research/THE-TOWER-SOURCES.md.\n' +
  'const TOWER_DATA = ' + JSON.stringify(data) + ';\n');
console.log('wrote', dest, (fs.statSync(dest).size / 1024).toFixed(0) + 'KB',
  Object.keys(data.workshop).length, 'workshop stats,', Object.keys(data.labs).length, 'labs');
